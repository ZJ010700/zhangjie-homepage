/** 把 "images/xxx.jpg" 拼上站点 base 前缀（GitHub Pages 子目录部署需要，不要改） */
export function asset(p: string): string {
  const base = import.meta.env.BASE_URL.endsWith("/")
    ? import.meta.env.BASE_URL
    : import.meta.env.BASE_URL + "/";
  return base + p.replace(/^\//, "");
}

